-- 1) AGENDAMENTOS
--    valor ................ preço do serviço no dia do agendamento (financeiro)
--    google_event_id ...... evento no Google Agenda (para mover/apagar)
--    lembrete_enviado_em .. quando o lembrete de 1 dia antes foi enviado
alter table public.appointments add column if not exists valor               numeric(10,2);
alter table public.appointments add column if not exists google_event_id     text;
alter table public.appointments add column if not exists lembrete_enviado_em timestamptz;

-- agendamentos antigos: usa o preço atual do catálogo como valor
update public.appointments a
set valor = s.preco
from public.services s
where a.service_id = s.id and a.valor is null and s.preco is not null;

create index if not exists appointments_data on public.appointments (appointment_date);
create index if not exists appointments_email on public.appointments (lower(client_email));

-- 2) CLIQUES NO WHATSAPP (garante a tabela e acelera o gráfico)
create table if not exists public.cliques_whatsapp (
  id        bigint generated by default as identity primary key,
  origem    text not null,
  campanha  text,
  criado_em timestamptz default now()
);
alter table public.cliques_whatsapp enable row level security;
create index if not exists cliques_whatsapp_data on public.cliques_whatsapp (criado_em);

-- 3) CONFIGURAÇÕES DO SITE (ex.: link "Avaliar no Google")
create table if not exists public.configuracoes (
  chave         text primary key,
  valor         text,
  atualizado_em timestamptz not null default now()
);
alter table public.configuracoes enable row level security;
revoke all on public.configuracoes from anon, authenticated;
-- sem policy: só o servidor do site lê e grava

-- 4) CONFERÊNCIA
select
  (select count(*) from public.appointments where valor is not null) as agendamentos_com_valor,
  (select count(*) from public.appointments)                         as agendamentos_total,
  (select count(*) from public.cliques_whatsapp)                     as cliques_registrados;
